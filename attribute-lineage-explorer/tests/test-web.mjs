import assert from 'node:assert/strict';
import fs from 'node:fs';
import {normalizeLineage,counts,traceNode,weakComponents} from '../graph-core.mjs';
const batch=JSON.parse(fs.readFileSync(new URL('../demo/lineage-all-edges.json', import.meta.url)));
const graph=normalizeLineage(batch), c=counts(graph);
assert.equal(c.nodes,86);assert.equal(c.localEdges,64);assert.equal(c.candidateCrossings,13);
const components=weakComponents(graph);
assert.equal(components.length,9);
assert.equal(components.reduce((a,c)=>a+c.length,0),c.nodes);
const find=ref=>[...graph.nodes.values()].find(n=>n.display_ref===ref);
const birth=find('UCP.db.individual.birthDate');
const bucket=find('AnalyticsUI.chart.ageBucket');
assert(birth&&bucket);
const t=traceNode(graph,birth.id,true);
assert(t.downstream.nodes.has(bucket.id));
assert.equal(t.candidateEdges.size,3);
assert.equal(t.nodes.size,21);
assert.equal(t.edges.size,20);
assert([...t.candidateEdges].every(id=>graph.edges.get(id).status==='candidate'));
const without=traceNode(graph,birth.id,false);
assert(!without.nodes.has(bucket.id));
assert.equal(without.candidateEdges.size,0);
assert([...without.edges].every(id=>graph.edges.get(id).kind==='local'));
const fromBucket=traceNode(graph,bucket.id,true);
assert(fromBucket.upstream.nodes.has(birth.id));
assert.equal(fromBucket.candidateEdges.size,3);
const full=find('KPK.mapper.composeFullName');
assert(full);
const merge=traceNode(graph,full.id,true);
assert([...merge.upstream.nodes].some(id=>graph.nodes.get(id).display_ref.includes('firstName')));
assert([...merge.upstream.nodes].some(id=>graph.nodes.get(id).display_ref.includes('lastName')));
const email=[...graph.nodes.values()].find(n=>n.repository_id==='analytics-ui'&&n.display_ref.includes('emailDomain'));
assert(email);
const emailTrace=traceNode(graph,email.id,true);
assert.equal(emailTrace.candidateEdges.size,0);
assert.throws(()=>traceNode(graph,'missing',true),/not in the graph/);
const bounded=traceNode(graph,birth.id,true,2);
assert(bounded.truncated);assert(bounded.nodes.size<=3); // each traversal has own limit 2, union can add a branch
console.log('PASS web: 9 components, full graph, reversible upstream/downstream, candidate filtering, no invented crossing, truncation');
