import fs from 'node:fs';
import assert from 'node:assert/strict';
import {normalizeLineage,parseLineage,counts,reachable} from '../graph-core.mjs';
const root=new URL('../',import.meta.url);
const load=n=>JSON.parse(fs.readFileSync(new URL('demo/'+n,root),'utf8'));
const batch=load('lineage-all-edges.json');
const g=normalizeLineage(batch),c=counts(g);
console.log('Batch fixture',c);
assert.deepEqual(c,{interactions:3,journeys:15,nodes:86,localEdges:64,candidateCrossings:13,gaps:16,unconnected:2});
assert.equal([...g.edges.values()].filter(e=>e.kind==='crossing' && e.status==='confirmed').length,0);
assert.equal([...g.journeys.filter(j=>j.raw.source_side.anchor_status==='resolved')].length,14);
assert.equal([...g.journeys.filter(j=>j.raw.target_side.anchor_status==='resolved')].length,14);
const birth=[...g.nodes.values()].find(n=>n.display_ref==='UCP.db.individual.birthDate');assert.ok(birth);
const focus=reachable(g,birth.id,'downstream');
const bucket=[...g.nodes.values()].find(n=>n.display_ref==='AnalyticsUI.chart.ageBucket');
assert.ok(bucket&&focus.nodeIds.has(bucket.id),'birthDate reaches ageBucket');
assert.equal([...focus.edgeIds].filter(id=>g.edges.get(id)?.kind==='crossing').length,3);
let cross=[...g.edges.values()].find(e=>e.kind==='crossing' && e.field_path==='customer.emailDomain');
assert.equal(cross,undefined,'unresolved emailDomain crossing not invented');
assert(g.diagnostics.some(d=>d.field_path==='customer.emailDomain'&&d.source_anchor_status==='unresolved'));
assert(g.diagnostics.some(d=>d.field_path==='individual.phone'&&d.target_anchor_status==='terminal'));
const single=normalizeLineage(load('lineage.json'));assert.equal(single.journeys.length,6);assert.equal(single.interactions.length,1);
assert.throws(()=>normalizeLineage({format:'fake',edges:[]}),/Unsupported JSON format/);
const missing=structuredClone(batch);delete missing.edges[0].result;assert.throws(()=>normalizeLineage(missing),/expected an object/);
const wrong=structuredClone(batch);wrong.edges[0].result.journeys[0].crossing.status='surprise';assert.throws(()=>normalizeLineage(wrong),/unknown crossing status/);
const conflict=structuredClone(batch);conflict.edges[0].result.journeys[0].source_side.query.result.paths[0].steps[0].source.display_ref='INVENTED';assert.throws(()=>normalizeLineage(conflict),/Identity conflict/);
console.log('PASS: batch, single, graph reachability, status invariants, gaps, negative validation');
